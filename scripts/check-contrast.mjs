#!/usr/bin/env node
// Checks every text/background and control pair the components use against
// WCAG 2.2 AA, reading colours straight from src/styles/tokens.css.
//
//   npm run contrast            check; fails on any failing pair or a stale record
//   npm run contrast -- --write regenerate docs/design/tokens.md
//
// Add a row to CONTRAST_PAIRS (src/lib/contrast.ts) whenever a component puts one token on another.

import { readFileSync, writeFileSync } from 'node:fs';
import {
  contrastRatio as ratio,
  CONTRAST_PAIRS as PAIRS,
  FORBIDDEN_PAIRS as FORBIDDEN,
  parseColourTokens,
} from '../src/lib/contrast.ts';

const TOKENS = 'src/styles/tokens.css';
const RECORD = 'docs/design/tokens.md';

function readTokens() {
  return parseColourTokens(readFileSync(TOKENS, 'utf8'));
}

function evaluate(tokens) {
  const missing = [];
  const rows = PAIRS.map(([fg, bg, min, use]) => {
    if (!tokens[fg] || !tokens[bg]) {
      missing.push(!tokens[fg] ? fg : bg);
      return null;
    }
    const r = ratio(tokens[fg], tokens[bg]);
    return { fg, bg, min, use, r, pass: r >= min };
  }).filter(Boolean);
  return { rows, missing };
}

function record(tokens, rows) {
  const fmt = (r) => r.toFixed(2);
  const lines = [
    '# Design tokens: contrast record',
    '',
    'Generated by `npm run contrast -- --write` from `src/styles/tokens.css`. Do not edit by hand; CI fails if this file is out of date.',
    '',
    'Standard: WCAG 2.2 AA. Text needs 4.5:1 (3:1 at 24px+ or 18.66px+ bold); UI components and focus indicators need 3:1. Public site: one dark theme ([ADR-0012](../adr/0012-dark-only-public-theme.md)).',
    '',
    '## Colour tokens',
    '',
    '| Token | Value |',
    '| --- | --- |',
    ...Object.entries(tokens).map(([k, v]) => `| \`--bc-${k}\` | \`${v}\` |`),
    '',
    '## Pairs in use',
    '',
    '| Foreground | Background | Ratio | Needs | Result | Used for |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (x) =>
        `| \`${x.fg}\` | \`${x.bg}\` | ${fmt(x.r)}:1 | ${x.min}:1 | ${x.pass ? 'Pass' : '**Fail**'} | ${x.use} |`,
    ),
    '',
    '## Never use',
    '',
    '| Foreground | Background | Ratio | Why |',
    '| --- | --- | --- | --- |',
    ...FORBIDDEN.filter(([fg, bg]) => tokens[fg] && tokens[bg]).map(
      ([fg, bg, why]) =>
        `| \`${fg}\` | \`${bg}\` | ${fmt(ratio(tokens[fg], tokens[bg]))}:1 | ${why} |`,
    ),
    '',
  ];
  return lines.join('\n');
}

const tokens = readTokens();
const { rows, missing } = evaluate(tokens);
const out = record(tokens, rows);
let failed = false;

if (missing.length) {
  failed = true;
  console.error(`✘ Unknown tokens in PAIRS: ${[...new Set(missing)].join(', ')}`);
}
for (const x of rows) {
  const line = `${x.pass ? '✔' : '✘'} ${x.r.toFixed(2).padStart(5)}:1 (needs ${x.min}:1) ${x.fg} on ${x.bg}`;
  if (x.pass) console.log(line);
  else {
    failed = true;
    console.error(line);
  }
}

if (process.argv.includes('--write')) {
  writeFileSync(RECORD, out);
  console.log(`Wrote ${RECORD}`);
} else {
  let current = '';
  try {
    current = readFileSync(RECORD, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // missing record is reported below
  }
  if (current !== out) {
    failed = true;
    console.error(`✘ ${RECORD} is out of date. Run: npm run contrast -- --write`);
  }
}

process.exit(failed ? 1 : 0);
